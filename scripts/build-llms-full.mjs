#!/usr/bin/env node
/* ==========================================================================
   build-llms-full.mjs — writes /llms-full.txt from the pages in sitemap.xml.

   llms.txt is the short summary an LLM reads first. llms-full.txt is the
   convention for "and here is everything": the Markdown rendering of every
   indexable page, one after another, so a model can load the whole site in
   one fetch instead of crawling twenty-five URLs.

   It uses the same converter as the edge function, so what a crawler gets
   from /about.md and what sits in llms-full.txt are identical.

   Run it after editing any page, then commit the result:

       node scripts/build-llms-full.mjs

   Pages are taken from sitemap.xml so a page that is deliberately kept out
   of the sitemap (noindex, retired) stays out of here too.
   ========================================================================== */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { htmlToMarkdown } from '../netlify/lib/html-to-markdown.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://infinityreachmedia.com';

const sitemap = readFileSync(join(root, 'sitemap.xml'), 'utf8');
const urls = [...sitemap.matchAll(/<loc>\s*([^<\s]+)\s*<\/loc>/g)].map((m) => m[1]);

const sections = [];
const skipped = [];

for (const url of urls) {
  const path = new URL(url).pathname;
  const file = path === '/' ? 'index.html' : `${path.replace(/^\//, '').replace(/\.html$/, '')}.html`;
  const full = join(root, file);
  if (!existsSync(full)) { skipped.push(`${url} (no ${file})`); continue; }

  const page = htmlToMarkdown(readFileSync(full, 'utf8'), { url });
  if (page.noindex) { skipped.push(`${url} (noindex)`); continue; }

  sections.push(page.markdown.trimEnd());
}

const header = [
  '# Infinity Reach Media: full site text',
  '',
  '> Every public page of https://infinityreachmedia.com rendered as Markdown,',
  '> in sitemap order. Each page begins with a front-matter block giving its',
  '> title, description and canonical URL. The short version is /llms.txt.',
  '> Any page is also available on its own by adding .md to its URL,',
  '> for example https://infinityreachmedia.com/about.md',
  '',
  `Pages: ${sections.length}. Generated by scripts/build-llms-full.mjs.`,
  '',
].join('\n');

const output = `${header}\n${sections.join('\n\n\n')}\n`;
writeFileSync(join(root, 'llms-full.txt'), output);

console.log(`llms-full.txt: ${sections.length} pages, ${output.length.toLocaleString()} characters`);
for (const s of skipped) console.log(`  skipped ${s}`);
